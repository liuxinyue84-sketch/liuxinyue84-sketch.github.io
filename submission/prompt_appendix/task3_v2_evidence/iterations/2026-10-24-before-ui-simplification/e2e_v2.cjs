'use strict';
const { chromium } = require('/Users/liuxinyue/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const fs=require('node:fs');
const path=require('node:path');
(async()=>{
 const root=path.resolve(__dirname,'../evaluation');
 const browser=await chromium.launch({headless:true,executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'});
 const page=await browser.newPage({viewport:{width:1512,height:1000},deviceScaleFactor:1});
 const errors=[]; const requests=[];
 page.on('pageerror',e=>errors.push(e.message));
 page.on('console',m=>{if(m.type()==='error' && !m.text().includes('Failed to load resource: the server responded with a status of 404')) errors.push(m.text())});
 page.on('request',r=>requests.push(r.url()));
 await page.goto('http://127.0.0.1:5584/#highlights',{waitUntil:'networkidle'});
 const outputs=[];
 async function choose(id){
  const button=page.locator(`[data-rag-query]`).nth(id);
  const query=await button.getAttribute('data-rag-query');
  await button.click();
  const refs=await page.locator('#rag-references').innerText();
  const ans=await page.locator('#rag-answer').innerText();
  const prompt=await page.locator('#rag-prompt').innerText();
  outputs.push({query,referenceText:refs,answerText:ans,promptIncludesQuery:prompt.includes(query),fallback:ans.includes('Insufficient reference materials to answer this question.')});
  return {refs,ans,prompt,fallback:ans.includes('Insufficient reference materials to answer this question.')};
 }
 const rag=await choose(0);
 if(!rag.refs.includes('RAG combines a pretrained LLM')) throw new Error('RAG clear-topic retrieval did not return the RAG definition');
 if(!rag.ans.includes('[R1]')) throw new Error('Generated answer lacks citation');
 await page.locator('.rag-v2-paper').screenshot({path:path.join(root,'evidence/V2-RAG-01_retrieved-answer-desktop.png')});
 const map=await choose(1);
 if(!map.refs.toLowerCase().includes('reducer') && !map.refs.toLowerCase().includes('mapreduce')) throw new Error('MapReduce query lacks relevant material');
 const memory=await choose(2);
 if(memory.fallback) throw new Error('Broad but topical memory query fell back');
 const vague=await choose(3);
 if(!vague.fallback) throw new Error(`Vague query did not abstain: ${vague.ans}`);
 await page.locator('.rag-v2-paper').screenshot({path:path.join(root,'evidence/V2-RAG-02_insufficient-materials-desktop.png')});
 const unrelated=await choose(4);
 if(!unrelated.fallback) throw new Error('Out-of-scope query did not abstain');
 const formQuery='How do I evaluate tool use by an LLM agent?';
 await page.locator('#rag-question').fill(formQuery);
 await page.locator('#rag-form button[type=submit]').click();
 const formAnswer=await page.locator('#rag-answer').innerText();
 const formRefs=await page.locator('#rag-references').innerText();
 if(!formRefs.includes('Tool Selection') || !formAnswer.includes('[R1]')) throw new Error('Typed form submission failed to retrieve/cite tool-use evidence');
 outputs.push({query:formQuery,referenceText:formRefs,answerText:formAnswer,promptIncludesQuery:(await page.locator('#rag-prompt').innerText()).includes(formQuery),fallback:false,interaction:'typed question and submitted form'});
 await page.locator('#rag-prompt-details summary').click();
 const promptVisible=await page.locator('#rag-prompt').isVisible();
 if(!promptVisible || !(await page.locator('#rag-prompt').innerText()).includes('RETRIEVED REFERENCE MATERIALS')) throw new Error('RAG prompt disclosure did not open');
 const logs=await page.locator('#rag-feedback').innerText();
 const externalRequests=requests.filter(url=>/^https?:/.test(url)&&!url.startsWith('http://127.0.0.1:5584'));
 if(errors.length) throw new Error(`Browser errors: ${errors.join(' | ')}`);
 const summary={version:'V2-RAG',date:new Date().toISOString(),timezone:'Asia/Hong_Kong',date_local:'2026-10-24',browser:'Google Chrome headless',viewport:'1512x1000 desktop',url:'http://127.0.0.1:5584/#highlights',testCount:6,tests:outputs,finalStatus:logs,consoleErrors:errors,nonblockingResourceMisses:['/favicon.ico returned 404; the V0 baseline has no favicon and this did not affect page or RAG behavior'],externalRequests,screenshots:['evidence/V2-RAG-01_retrieved-answer-desktop.png','evidence/V2-RAG-02_insufficient-materials-desktop.png']};
 fs.writeFileSync(path.join(root,'e2e_results_v2.json'),JSON.stringify(summary,null,2));
 console.log(JSON.stringify({passed:true,testCount:6,errors,externalRequests,screenshots:['V2-RAG-01_retrieved-answer-desktop.png','V2-RAG-02_insufficient-materials-desktop.png']}));
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
